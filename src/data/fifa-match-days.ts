export const TOURNAMENT_START = "2026-06-11";
export const TOURNAMENT_END = "2026-07-19";

export function getFifaMatchDay(externalId: number): string | undefined {
  return FIFA_MATCH_DAYS[externalId];
}

export function getExternalIdsForFifaDay(day: string): number[] {
  return Object.entries(FIFA_MATCH_DAYS)
    .filter(([, d]) => d === day)
    .map(([id]) => Number(id));
}

export function isTournamentCalendarDay(day: string): boolean {
  return day >= TOURNAMENT_START && day <= TOURNAMENT_END;
}
